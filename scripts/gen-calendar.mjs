// Generates src/data/calendar2027.ts (language-neutral day data) from the verified
// source tables in scripts/calendar2027/ (see README there for sources and rules).
//   node scripts/gen-calendar.mjs
// Dates and tag ids are language-neutral on purpose: labels live in src/data/calendarText.*.ts,
// so a translation gap can never shift a date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(here, 'calendar2027', 'calendar2027.json'), 'utf8'));

const koyomiMap = {
  '天赦日': 'tensha', '一粒万倍日': 'ichiryumanbai', '寅の日': 'tora',
  '巳の日': 'mi', '己巳の日': 'tsuchinotomi', '甲子の日': 'kinoene',
};
const holidayMap = {
  '元日': 'ganjitsu', '成人の日': 'seijin', '建国記念の日': 'kenkoku', '天皇誕生日': 'tennou',
  '春分の日': 'shunbun', '休日(振替休日)': 'furikae', '昭和の日': 'showa', '憲法記念日': 'kenpou',
  'みどりの日': 'midori', 'こどもの日': 'kodomo', '海の日': 'umi', '山の日': 'yama',
  '敬老の日': 'keirou', '秋分の日': 'shubun', 'スポーツの日': 'sports', '文化の日': 'bunka', '勤労感謝の日': 'kinrou',
};
const sekkiMap = {
  '小寒': 'shokan', '大寒': 'daikan', '立春': 'risshun', '雨水': 'usui', '啓蟄': 'keichitsu', '春分': 'shunbun',
  '清明': 'seimei', '穀雨': 'kokuu', '立夏': 'rikka', '小満': 'shoman', '芒種': 'boshu', '夏至': 'geshi',
  '小暑': 'shousho', '大暑': 'taisho', '立秋': 'risshuu', '処暑': 'shosho', '白露': 'hakuro', '秋分': 'shubun',
  '寒露': 'kanro', '霜降': 'soukou', '立冬': 'ritto', '小雪': 'shosetsu', '大雪': 'taisetsu', '冬至': 'toji',
};
const zassetsuMap = {
  '土用の入り(冬)': 'doyo-fuyu', '節分': 'setsubun', '彼岸の入り(春)': 'higan-haru', '土用の入り(春)': 'doyo-haru',
  '八十八夜': 'hachijuhachiya', '入梅': 'nyubai', '半夏生': 'hangesho', '土用の入り(夏)': 'doyo-natsu',
  '二百十日': 'nihyakutoka', '彼岸の入り(秋)': 'higan-aki', '土用の入り(秋)': 'doyo-aki',
};
const derivedMap = { '初午': 'hatsuuma', '夏の土用の丑の日': 'doyo-ushi' };
const moonMap = { '朔(新月)': 'new', '望(満月)': 'full' };

const days = [];
for (const r of src) {
  const day = { date: r.date };
  const koyomi = r.tags.map((t) => koyomiMap[t]);
  if (koyomi.some((k) => !k)) throw new Error(`unknown koyomi tag on ${r.date}: ${r.tags}`);
  if (koyomi.length) day.koyomi = koyomi;
  const zass = [];
  for (const o of r.official) {
    const [kind, ...rest] = o.split(':');
    const val = rest.join(':');
    if (kind === '祝日') { if (!holidayMap[val]) throw new Error(`holiday ${val}`); day.holiday = holidayMap[val]; }
    else if (kind === '二十四節気') { if (!sekkiMap[val]) throw new Error(`sekki ${val}`); day.sekki = sekkiMap[val]; }
    else if (kind === '雑節') { if (!zassetsuMap[val]) throw new Error(`zassetsu ${val}`); zass.push(zassetsuMap[val]); }
    else if (kind === '月相') { if (!moonMap[val]) throw new Error(`moon ${val}`); day.moon = moonMap[val]; }
    else throw new Error(`unknown official kind ${o}`);
  }
  for (const d of r.derived) {
    const key = derivedMap[d] ?? (d === '二の午' ? null : undefined);
    if (key === undefined) throw new Error(`unknown derived ${d}`);
    if (key) zass.push(key);
  }
  if (zass.length) day.zassetsu = zass;
  if (day.koyomi || day.holiday || day.sekki || day.zassetsu || day.moon) days.push(day);
}

const out = `// AUTO-GENERATED by scripts/gen-calendar.mjs — do not edit by hand.
// Sources and rules: scripts/calendar2027/README.md
// 公的発表: 内閣府(祝日)・国立天文台 暦要項 令和9年(二十四節気・雑節・朔望)。暦注(koyomi)は慣習で公式ではない。
export type KoyomiTag = 'tensha' | 'ichiryumanbai' | 'tora' | 'mi' | 'tsuchinotomi' | 'kinoene';
export interface CalendarDay {
  /** YYYY-MM-DD */
  date: string;
  /** 暦注（慣習・公式ではない） */
  koyomi?: KoyomiTag[];
  /** 国民の祝日（内閣府） */
  holiday?: string;
  /** 二十四節気（国立天文台 暦要項） */
  sekki?: string;
  /** 雑節など（国立天文台 暦要項／日支からの算出） */
  zassetsu?: string[];
  /** 朔(new)・望(full)（国立天文台 暦要項） */
  moon?: 'new' | 'full';
}
export const calendarYear = 2027;
export const calendarDays: CalendarDay[] = ${JSON.stringify(days, null, 2)};
`;
fs.writeFileSync(path.join(here, '..', 'src', 'data', 'calendar2027.ts'), out);
console.log(`calendar2027.ts: ${days.length} annotated days (of ${src.length})`);

// ---- 六曜（参考ページ用）: scripts/calendar2027/rokuyo2027.json があれば rokuyo2027.ts も生成する ----
const rokuyoPath = path.join(here, 'calendar2027', 'rokuyo2027.json');
if (fs.existsSync(rokuyoPath)) {
  const rk = JSON.parse(fs.readFileSync(rokuyoPath, 'utf8'));
  const keyOf = { '先勝': 'senshou', '友引': 'tomobiki', '先負': 'senbu', '仏滅': 'butsumetsu', '大安': 'taian', '赤口': 'shakku' };
  const entries = Object.entries(rk).map(([date, v]) => {
    if (!keyOf[v.rokuyo]) throw new Error(`unknown rokuyo ${v.rokuyo} on ${date}`);
    return `  '${date}': ['${keyOf[v.rokuyo]}', '${v.kyureki}'],`;
  });
  const rout = `// AUTO-GENERATED by scripts/gen-calendar.mjs — do not edit by hand.
// 六曜は旧暦の月日から決まる暦注（公式ではない）。旧暦は国立天文台 暦要項の朔・二十四節気から求めた。
// 根拠・照合結果: scripts/calendar2027/README.md
import type { RokuyoKey } from './calendarText.ja';
/** 日付 → [六曜, 旧暦の月-日（閏月は先頭に L）] */
export const rokuyoByDate: Record<string, [RokuyoKey, string]> = {
${entries.join('\n')}
};
`;
  fs.writeFileSync(path.join(here, '..', 'src', 'data', 'rokuyo2027.ts'), rout);
  console.log(`rokuyo2027.ts: ${entries.length} days`);
}
