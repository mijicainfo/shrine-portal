export interface TripHotelTarget {
  cityId: number;
  /** Trip.com の display / optionName に入れる、日本語の地名（例: 京都市） */
  name: string;
  /** trip_sub1 に入れる識別タグ（例: shrine-yabo-tenmangu） */
  tag?: string;
  /** 「遊び・体験」の市の番号（sitedistid）。Trip.com側に市の一覧がない市は undefined（Klookにフォールバック） */
  activityId?: number;
}

/**
 * ja の `prefecture` と `city` から、対応表のキー（`都道府県|市区町村`）を作る。
 * 東京都は23区をまとめて「東京都」（市部は「東京都|調布市」のように市ごと）、
 * それ以外は「◯◯市」まで（郡の町村はそのまま）に丸める。
 */
export function tripCityKey(prefecture: string, city: string): string {
  const c = city.replace(/[（(].*?[）)]/g, '').trim();
  if (prefecture === '東京都') return c.endsWith('区') ? '東京都|東京都' : `東京都|${c}`;
  const m = c.match(/^(.+?市)/);
  return `${prefecture}|${m ? m[1] : c}`;
}

export function findTripTarget(prefecture: string, city: string, tag?: string): TripHotelTarget | undefined {
  const key = tripCityKey(prefecture, city);
  const cityId = tripCityIds[key];
  if (!cityId) return undefined;
  return { cityId, name: key.split('|')[1], tag, activityId: tripActivityCityIds[key] };
}

export function buildTripcomHotelUrl(lang: TripLang, target: TripHotelTarget): string {
  const domain = tripcomDomains[lang];
  const name = encodeURIComponent(target.name);
  const tag = encodeURIComponent(target.tag ?? '');
  return (
    `https://${domain}/hotels/list?city=${target.cityId}&display=${name}&optionId=${target.cityId}` +
    `&optionType=City&optionName=${name}&Allianceid=${tripcomConfig.allianceId}&SID=${tripcomConfig.siteId}` +
    `&trip_sub1=${tag}&trip_sub3=${tripcomConfig.trackingIds[lang]}`
  );
}

/**
 * 「遊び・体験」の市の一覧ページへのリンク。日本語ページ以外で使う（日本語は引き続きKlook）。
 * activityId がない場合は undefined（呼び出し側がKlookにフォールバックする）。
 */
export function buildTripcomActivitiesUrl(lang: TripLang, target: TripHotelTarget): string | undefined {
  if (lang === 'ja' || !target.activityId) return undefined;
  const tag = encodeURIComponent(target.tag ?? '');
  return (
    `https://${tripcomDomains[lang]}/things-to-do/list?pagetype=city&districttype=3&sitedistid=${target.activityId}` +
    `&Allianceid=${tripcomConfig.allianceId}&SID=${tripcomConfig.siteId}&trip_sub1=${tag}&trip_sub3=${tripcomConfig.trackingIds[lang]}`
  );
}

