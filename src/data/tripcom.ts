export type TripLang = 'ja' | 'en' | 'zh' | 'es' | 'fr' | 'ko';

export function isTripLang(lang: string): lang is TripLang {
  return lang === 'ja' || lang === 'en' || lang === 'zh' || lang === 'es' || lang === 'fr' || lang === 'ko';
}

/** 言語ごとの Trip.com のドメイン（ツールの「リンクの言語」に対応）。ここにない言語では使わない。 */
